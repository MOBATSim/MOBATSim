function MOBATSimAutoTesting(options)
%MOBATSim TEST Script: Simulation-based testing with different driving scenarios.
%   All scenarios have to produce the [PASSED] as the output without errors

% Contributors: Johannes Pintscher, Mustafa Saraoglu

    arguments
        options.simStopTime         (1,1) double    = 120   % Time to test the scenarios in seconds
        options.firstScenarioID     (1,1) double    = 1     % Start from scenario i
        options.lastScenarioID      (1,1) double    = 30    % Simulate until scenario j
        options.collisionReport     (1,1) double    = 0     % Outputs collision report
        options.IM_Mode             (1,1) IM_Algorithm_Enum = IM_Algorithm_Enum.IntelligentDecision % The intersection management algorithm mode
        options.scenarioNames       (1,:) string    = [ "Urban City Traffic", ...
                                                        "Curved Road Overtaking", ...
                                                        "Merge Collision", ...
                                                        "Platoon Control", ...
                                                        "High Speed Collision", ...
                                                        "Collision Merge", ...
                                                        "Complex Crossroad", ...
                                                        "Extra Complex Crossroad", ...
                                                        "Counterexample Crossroad Safety", ...
                                                        "Mayhem", ...
                                                        "Convoy Platoons", ...
                                                        "Vehicle Safety Filter Test", ...
                                                        "Scenario 13", ...
                                                        "Scenario 14", ...
                                                        "Scenario 15", ...
                                                        "Scenario 16", ...
                                                        "Scenario 17", ...
                                                        "Scenario 18", ...
                                                        "Scenario 19", ...
                                                        "Scenario 20", ...
                                                        "Scenario 21", ...
                                                        "Scenario 22", ...
                                                        "Scenario 23", ...
                                                        "Scenario 24", ...
                                                        "Scenario 25", ...
                                                        "Scenario 26", ...
                                                        "Scenario 27", ...
                                                        "Scenario 28", ...
                                                        "Scenario 29", ...
                                                        "Scenario 30"];     % Scenarios to test
    end

    % List of results for every scenario
    passed = strings(size(options.scenarioNames));
    % Make or open a text file for the report
    fileID = fopen('AutoTestReport.txt','w');
    % Header
    fprintf(fileID,'Automatic Test Report\n\r');
    
    %% Timer starts
    tic;
    
    %% Which scenarios are simulated - All or a custom range
    if (options.firstScenarioID==1) && (options.lastScenarioID==length(options.scenarioNames))
        disp('All scenarios will be simulated...');
    else
        % Custom range of scenarios defined by the user
        disp('Only the specified scenarios will be simulated...');
    end
    
    j = 0;
    %% Test each scenario
    for i=options.firstScenarioID:options.lastScenarioID
        j = j + 1;
        try
            % prepare and run simulation
            prepare_simulator("scenarioName",options.scenarioNames(i),"collisionReport",options.collisionReport,"IM_Mode", options.IM_Mode,"simStopTime",options.simStopTime);
            mpcverbosity off; % Make sure that the MPC doesn't fill the command window
            run_Sim();
            passed(j) = "PASSED";
        catch ME
            passed(j) = "ERROR";
        end

        % Display scenario name and if passed    
        disp("<strong>" + options.scenarioNames(i) + ":</strong>" + " [" + passed(j) +"]");
        % Add this information also to the report
        fprintf(fileID,'%s: [%s]\n',options.scenarioNames(i),passed(j));

        % Display only the exception message, but dont interrupt the execution
        if  passed(j) ~= "PASSED"
            fprintf(2,ME.cause{1}.message + "\n");
        end
    end
    % Finish and close the report
    fclose(fileID);
    toc;
end

